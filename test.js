const http = require('http');
const mongoose = require('mongoose');
const { MongoMemoryServer } = require('mongodb-memory-server');

process.env.NODE_ENV = 'test';
process.env.PORT = '3000';

let mongod;
let app;
let server;
let Task;

function request(path, options = {}) {
  return new Promise((resolve, reject) => {
    const defaultHeaders = {};
    if (options.body && options.headers === undefined) {
      defaultHeaders['Content-Type'] = 'application/json';
    }

    const reqOptions = {
      hostname: '127.0.0.1',
      port: 3000,
      path: path,
      method: options.method || 'GET',
      headers: Object.assign({}, defaultHeaders, options.headers || {})
    };

    const req = http.request(reqOptions, (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        let json;
        try {
          json = JSON.parse(data);
        } catch {
          json = data;
        }
        resolve({
          statusCode: res.statusCode,
          headers: res.headers,
          body: json
        });
      });
    });

    req.on('error', reject);

    if (options.body !== undefined) {
      const payload = typeof options.body === 'string' ? options.body : JSON.stringify(options.body);
      req.write(payload);
    }
    req.end();
  });
}

async function runTests() {
  console.log('\n========================================================================');
  console.log('   Practical 5: MongoDB Integration & Mongoose Schema Tests (24IT055)   ');
  console.log('========================================================================\n');

  // Start in-memory MongoDB server
  mongod = await MongoMemoryServer.create({ instance: { port: 27017 } });
  const uri = mongod.getUri() + 'test';
  process.env.MONGO_URI = uri;
  console.log('✔ MongoDB Server started at:', uri);

  // Require server and model after setting MONGO_URI
  const serverModule = require('./server');
  app = serverModule.app;
  Task = require('./models/Task');

  // Start listening on port 3000
  server = app.listen(3000, () => {
    console.log('✔ Express API listening on http://localhost:3000\n');
  });

  // Wait for mongoose connection
  await new Promise((resolve) => {
    if (mongoose.connection.readyState === 1) resolve();
    else mongoose.connection.once('open', resolve);
  });

  let passed = 0;
  let total = 0;
  let createdTaskId = null;

  async function test(name, fn) {
    total++;
    try {
      await fn();
      console.log(` \x1b[32m✔ PASS\x1b[0m [Step ${total}] ${name}`);
      passed++;
    } catch (err) {
      console.log(` \x1b[31m✘ FAIL\x1b[0m [Step ${total}] ${name}`);
      console.error(`   Error: ${err.message}`);
    }
  }

  function assert(condition, message) {
    if (!condition) throw new Error(message || 'Assertion failed');
  }

  try {
    // Test 1: POST /tasks (Create Task)
    await test('POST /tasks: creates a task in MongoDB (status 201 Created)', async () => {
      const res = await request('/tasks', {
        method: 'POST',
        body: {
          title: 'Complete MongoDB Practical',
          description: 'Implement CRUD operations using Mongoose',
          completed: false
        }
      });
      assert(res.statusCode === 201, `Expected status 201, got ${res.statusCode}`);
      assert(res.body._id, 'Response should contain _id generated by MongoDB');
      assert(res.body.title === 'Complete MongoDB Practical', 'Title should match input');
      assert(res.body.completed === false, 'Completed should default to false');
      assert(res.body.createdAt, 'Response should contain createdAt timestamp');
      createdTaskId = res.body._id;
    });

    // Test 2: GET /tasks (Get All Tasks)
    await test('GET /tasks: returns tasks from live MongoDB (status 200 OK)', async () => {
      const res = await request('/tasks');
      assert(res.statusCode === 200, `Expected status 200, got ${res.statusCode}`);
      assert(Array.isArray(res.body), 'Response should be an array');
      assert(res.body.length === 1, `Expected 1 task in database, found ${res.body.length}`);
      assert(res.body[0]._id === createdTaskId, 'Retrieved task ID should match created task');
    });

    // Test 3: GET /tasks/:id (Get Single Task)
    await test('GET /tasks/:id: returns specific task by MongoDB ObjectId (status 200 OK)', async () => {
      const res = await request(`/tasks/${createdTaskId}`);
      assert(res.statusCode === 200, `Expected status 200, got ${res.statusCode}`);
      assert(res.body._id === createdTaskId, 'Retrieved task ID should match');
      assert(res.body.title === 'Complete MongoDB Practical', 'Task title should match');
    });

    // Test 4: PUT /tasks/:id (Update Task)
    await test('PUT /tasks/:id: updates task completed status (status 200 OK)', async () => {
      const res = await request(`/tasks/${createdTaskId}`, {
        method: 'PUT',
        body: {
          completed: true
        }
      });
      assert(res.statusCode === 200, `Expected status 200, got ${res.statusCode}`);
      assert(res.body.completed === true, 'Task completed status should be true');
      
      // Verify directly from MongoDB
      const dbDoc = await Task.findById(createdTaskId);
      assert(dbDoc.completed === true, 'MongoDB document completed field should be true');
    });

    // Test 5: Validation Error (Missing Title)
    await test('POST /tasks without title: returns structured JSON validation error (status 400)', async () => {
      const res = await request('/tasks', {
        method: 'POST',
        body: {
          description: 'No title provided'
        }
      });
      assert(res.statusCode === 400, `Expected status 400, got ${res.statusCode}`);
      assert(res.body.message === 'Validation Error', 'Should return structured message "Validation Error"');
      assert(Array.isArray(res.body.errors), 'Should return structured errors array, not raw Mongoose error');
    });

    // Test 6: Pre-save hook & Trim
    await test('Pre-save hook: trims leading and trailing whitespace from title', async () => {
      const res = await request('/tasks', {
        method: 'POST',
        body: {
          title: '   Untrimmed Title With Whitespace   ',
          description: 'Testing pre-save hook'
        }
      });
      assert(res.statusCode === 201, `Expected status 201, got ${res.statusCode}`);
      assert(res.body.title === 'Untrimmed Title With Whitespace', `Expected trimmed title, got "${res.body.title}"`);
      // Clean up test task
      await Task.findByIdAndDelete(res.body._id);
    });

    // Test 7: Enum Validation for priority
    await test('Enum validation: rejects invalid priority values (status 400)', async () => {
      const res = await request('/tasks', {
        method: 'POST',
        body: {
          title: 'Invalid Priority Task',
          priority: 'urgent' // Valid are low, medium, high
        }
      });
      assert(res.statusCode === 400, `Expected status 400, got ${res.statusCode}`);
      assert(res.body.message === 'Validation Error', 'Should reject invalid priority enum');
    });

    // Test 8: GET non-existent ID (404 Handling)
    await test('GET /tasks/:id: returns 404 JSON response when task not found', async () => {
      const nonExistentId = new mongoose.Types.ObjectId();
      const res = await request(`/tasks/${nonExistentId}`);
      assert(res.statusCode === 404, `Expected status 404, got ${res.statusCode}`);
      assert(res.body.message === 'Task not found', 'Should return structured 404 JSON response');
    });

    // Test 9: DELETE /tasks/:id (Delete Task)
    await test('DELETE /tasks/:id: deletes task from database (status 200 OK)', async () => {
      const res = await request(`/tasks/${createdTaskId}`, {
        method: 'DELETE'
      });
      assert(res.statusCode === 200, `Expected status 200, got ${res.statusCode}`);
      assert(res.body.message === 'Task deleted successfully', 'Response should confirm deletion');
      assert(res.body.task._id === createdTaskId, 'Deleted task details should be returned');
    });

    // Test 10: GET /tasks after delete (Empty database)
    await test('GET /tasks after delete: confirms collection is empty (status 200 OK)', async () => {
      const res = await request('/tasks');
      assert(res.statusCode === 200, `Expected status 200, got ${res.statusCode}`);
      assert(res.body.length === 0, 'Database collection should now be empty');
    });

  } finally {
    if (server) server.close();
    await mongoose.disconnect();
    if (mongod) await mongod.stop();

    console.log('\n------------------------------------------------------------------------');
    console.log(` Results: ${passed} of ${total} tests passed (${Math.round((passed/total)*100)}%)`);
    console.log('------------------------------------------------------------------------\n');
    if (passed !== total) process.exit(1);
  }
}

runTests();
